    /// Dil etiketini desteklenen koda eşler (`de-AT` → `de`, `pt` → `pt-BR`, `zh-Hans-CN` → `zh-CN`); yoksa `en`.
    public static func resolve(_ language: String?) -> String {
        let norm = (language ?? "").replacingOccurrences(of: "_", with: "-").lowercased()
        if norm.isEmpty { return "en" }
        if let exact = table.keys.first(where: { $0.lowercased() == norm }) { return exact }
        let primary = norm.split(separator: "-").first.map(String.init) ?? norm
        if primary == "zh" {
            let parts = Set(norm.split(separator: "-").map(String.init))
            return parts.isDisjoint(with: ["hant", "tw", "hk", "mo"]) ? "zh-CN" : "en"
        }
        if primary == "pt" { return "pt-BR" }
        return table.keys.first(where: { $0.lowercased() == primary }) ?? "en"
    }

    /// Cihazın tercih ettiği dil (uygulamanın ilk tercih dili).
    public static var deviceLanguage: String { resolve(Locale.preferredLanguages.first) }

    /// Metin; `{ad}` yer tutucuları `args` ile doldurulur.
    public static func text(_ key: String, language: String? = nil, args: [String: String] = [:]) -> String {
        let code = language.map(resolve) ?? deviceLanguage
        var value = table[code]?[key] ?? table["en"]?[key] ?? key
        for (name, arg) in args { value = value.replacingOccurrences(of: "{\(name)}", with: arg) }
        return value
    }
